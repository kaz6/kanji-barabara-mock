# 組み合わせごとの読みの手直し（上の表の組み立てでは足りないもの）
OVERRIDE = {"二十日": ["はつか"]}
# 自信の無いもの：実際にはあまり言わない組み合わせ（百・千・万＋月・時）と、読みが複数あって代表を決めきれない2字の数の日
Q_COUNTERS_BIG = {"月", "時"}


def numbers():
    out = [(n, VAL[n], None) for n in SINGLE]
    out += [(t + "十", None, ("tens", t)) for t in TENS]       # 二十〜九十
    out += [("十" + u, None, ("teen", u)) for u in SINGLE[:9]]  # 十一〜十九
    return out


def readings(num, spec, c):
    s = C[c]
    if len(num) == 1:
        return list(s["single"][VAL[num]])
    cmp_ = dict(s["single"]); cmp_.update(s.get("cmp", {}))
    if spec[0] == "tens":  # 二十 など：数の読み＋じゅう（の形）
        pre = PRE[VAL[spec[1]]]
        tail = cmp_[10]
        return [pre + t for t in tail]
    pre = "じゅう"          # 十一 など：じゅう＋その字（二十の次は 21〜 は数が3字になるので扱わない）
    return [pre + t for t in cmp_[VAL[spec[1]]]]


def write_doc(d):
    """docs/COUNTERS.md（読みの一覧。作り直すと上書き。作者が赤を入れるときは、このスクリプトの表を直す）"""
    q = set(d["q"])
    lines = ["# 数＋助数詞の読み（KJ-022・D-040）", "",
             "`python3 tools/build_counters.py` で作り直す（このファイルは上書きされる。読みを直すときは tools/build_counters.py の表を直す）。",
             "辞書に無くても、数＋助数詞（数＝一〜十・百・千・万、2字は 二十〜九十・十一〜十九）は言葉として放てる。点数は字数どおり（2字3点・3字9点）。",
             "一度放った言葉に使った助数詞は、その試合ではもう 数＋助数詞 に使えない（辞書にある 百円・一人 なども数える。二人とも同じ）。",
             "読みは、あるだけ「・」でつなぐ（先頭が代表）。？ は読みに自信が無い、または実際にはあまり言わない組み合わせ。", ""]
    lines.append(f"助数詞（{len(d['counters'])}）：" + "・".join(d["counters"]) + "（字が N5・N4 にあるものだけ。階・番・枚・個・匹・歳・冊・課 は N5・N4 に無いので入れていない）")
    lines.append(f"数：{len(d['numbers'])} + {len(d['numbers2'])} = {len(d['numbers']) + len(d['numbers2'])}。組み合わせ：{len(d['readings'])}。？：{len(q)}")
    lines.append("")
    nums = d["numbers"] + d["numbers2"]
    for c in d["counters"]:
        lines.append(f"## {c}")
        lines.append("")
        lines.append("| 言葉 | 読み |")
        lines.append("|---|---|")
        for n in nums:
            w = n + c
            lines.append(f"| {w}{' ？' if w in q else ''} | {'・'.join(d['readings'][w])} |")
        lines.append("")
    with open(os.path.join(ROOT, "docs", "COUNTERS.md"), "w", encoding="utf8") as f:
        f.write("\n".join(lines))


def main():
    kanji = json.load(open(os.path.join(ROOT, "data", "kanji.json"), encoding="utf8"))
    lv = {k["c"]: k.get("lv") for k in kanji["kanji"]}
    counters = [c for c in C if lv.get(c) in ("N5", "N4")]
    assert counters == list(C), "N5・N4 に無い助数詞が混ざっている：" + str(set(C) - set(counters))
    rd, q = {}, []
    for num, _, spec in numbers():
        for c in counters:
            w = num + c
            r = readings(num, spec, c)
            if w in OVERRIDE:
                r = OVERRIDE[w]
            rd[w] = r
            if c in Q_COUNTERS_BIG and len(num) == 1 and VAL[num] >= 100:
                q.append(w)
    out = {
        "version": 1,
        "note": "数＋助数詞（KJ-022・D-040）。tools/build_counters.py で作る。数＝numbers（1字）と numbers2（2字）、助数詞＝counters。"
                "一度放った言葉に使った助数詞は、その試合ではもう「数＋助数詞」に使えない。readings＝組み合わせごとの読み（先頭が代表）、q＝読みに自信の無い組み合わせ",
        "numbers": SINGLE,
        "numbers2": [n for n, _, spec in numbers() if spec],
        "counters": counters,
        "readings": rd,
        "q": q,
    }
    path = os.path.join(ROOT, "data", "counters.json")
    with open(path, "w", encoding="utf8") as f:
        json.dump(out, f, ensure_ascii=False, indent=0, separators=(",", ":"))
        f.write("\n")
    write_doc(out)
    print("counters", len(counters), "numbers", len(SINGLE), "+", len(out["numbers2"]), "combos", len(rd), "q", len(q))


if __name__ == "__main__":
    main()
