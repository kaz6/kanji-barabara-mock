import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

SINGLE = ["一", "二", "三", "四", "五", "六", "七", "八", "九", "十", "百", "千", "万"]
TENS = ["二", "三", "四", "五", "六", "七", "八", "九"]  # 二十〜九十
